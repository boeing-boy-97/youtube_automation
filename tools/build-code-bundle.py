#!/usr/bin/env python3
"""Build a single self-contained HTML file containing every source file of the project.

The platform's file viewer renders one file at a time, so "where is the whole code?" has an
awkward answer: in 130+ files. This bundles them into one browsable page — file tree on the left,
code on the right, client-side search and per-file collapse. No external CSS, JS, fonts or images,
so it renders identically offline and inside a sandboxed preview.

Usage:  .venv/bin/python tools/build-code-bundle.py [output.html]
"""
from __future__ import annotations

import html
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = Path("/home/user/clipforge-ai-code.html")

INCLUDE_EXT = {".ts", ".tsx", ".py", ".prisma", ".json", ".yml", ".yaml", ".sh", ".css", ".md", ".sql", ".mjs"}
EXCLUDE_DIRS = {"node_modules", ".venv", ".next", ".git", "dist", "build", "__pycache__", "local-storage", ".arena", ".cache", "coverage"}


def tracked_files() -> list[Path]:
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    paths = []
    for line in out.split("\n"):
        if not line:
            continue
        path = ROOT / line
        if any(part in EXCLUDE_DIRS for part in path.parts):
            continue
        if path.suffix not in INCLUDE_EXT or not path.is_file():
            continue
        if path.name in {"package-lock.json", "tsconfig.tsbuildinfo"}:
            continue
        paths.append(path)
    return sorted(paths, key=lambda p: str(p.relative_to(ROOT)))


def build(output: Path) -> Path:
    files = tracked_files()
    total_lines = sum(len(p.read_text(errors="ignore").splitlines()) for p in files)
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()

    parts: list[str] = [
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>",
        "<meta name='viewport' content='width=device-width,initial-scale=1'>",
        "<title>ClipForge AI — complete source</title>",
        """<style>
:root{--bg:#0f1218;--panel:#161b23;--line:#242c38;--ink:#e6ebf2;--dim:#93a1b5;--accent:#4f8cff;--mono:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--ink);font:14px/1.55 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif}
header{padding:18px 22px;border-bottom:1px solid var(--line);background:var(--panel);position:sticky;top:0;z-index:5}
h1{margin:0;font-size:17px;letter-spacing:.2px}
.meta{margin-top:4px;color:var(--dim);font-size:12.5px}
.wrap{display:flex;align-items:flex-start;gap:0}
nav{width:310px;min-width:310px;height:calc(100vh - 74px);overflow:auto;border-right:1px solid var(--line);padding:10px 8px;position:sticky;top:74px}
nav a{display:block;padding:3px 8px;border-radius:6px;color:var(--dim);text-decoration:none;font:12.5px/1.4 var(--mono);white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
nav a:hover{background:#1d2530;color:var(--ink)}
.searchbox{width:100%;margin:2px 0 10px;padding:7px 9px;border-radius:7px;border:1px solid var(--line);background:#0b0e13;color:var(--ink);font:13px var(--mono)}
main{flex:1;padding:18px 22px 60px;min-width:0}
details{background:var(--panel);border:1px solid var(--line);border-radius:10px;margin-bottom:12px;overflow:hidden}
details[open]{border-color:#2e3a4d}
summary{cursor:pointer;padding:10px 14px;font:13px var(--mono);color:var(--ink);display:flex;justify-content:space-between;gap:12px;align-items:center;list-style:none}
summary::-webkit-details-marker{display:none}
summary .p{white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
summary .n{color:var(--dim);font-size:11.5px;white-space:nowrap}
pre{margin:0;padding:12px 14px;overflow:auto;background:#0b0e13;border-top:1px solid var(--line);font:12px/1.5 var(--mono);tab-size:2}
code{white-space:pre}
.hidden{display:none}
.legend{padding:8px 10px;color:var(--dim);font-size:12px;border:1px dashed var(--line);border-radius:8px;margin-bottom:14px}
</style></head><body>""",
        f"<header><h1>ClipForge AI — complete source</h1><div class='meta'>{len(files)} files · {total_lines:,} lines · commit {head} · generated by tools/build-code-bundle.py</div></header>",
        "<div class='wrap'><nav><input class='searchbox' id='q' placeholder='Filter files…' aria-label='Filter files'><div id='list'></div></nav><main>",
        "<div class='legend'>Click a file to expand it. Every file below is the real content read from the repository — nothing is summarised.</div>",
    ]

    for index, path in enumerate(files):
        rel = str(path.relative_to(ROOT))
        text = path.read_text(errors="ignore")
        loc = len(text.splitlines())
        parts.append(
            f"<details id='f{index}'><summary><span class='p'>{html.escape(rel)}</span><span class='n'>{loc} lines</span></summary>"
            f"<pre><code>{html.escape(text)}</code></pre></details>"
        )

    links = "".join(
        f"<a href='#f{i}' data-path='{html.escape(str(p.relative_to(ROOT)).lower())}'>{html.escape(str(p.relative_to(ROOT)))}</a>"
        for i, p in enumerate(files)
    )
    parts.append("</main></div>")
    parts.append(
        f"<script>const list=document.getElementById('list');list.innerHTML={links!r};"
        "const links=[...list.querySelectorAll('a')];document.getElementById('q').addEventListener('input',e=>{"
        "const v=e.target.value.trim().toLowerCase();links.forEach(a=>{a.classList.toggle('hidden',v.length>0&&!a.dataset.path.includes(v))})});"
        "</script></body></html>"
    )

    output.write_text("\n".join(parts))
    return output


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    written = build(out)
    print(f"wrote {written} ({written.stat().st_size / 1024:.0f} KB)")
